ALL_QUESTIONS = [
    {**question, "category": category_id, "category_title": category["title"]}
    for category_id, category in FAQ.items()
    for question in category["questions"]
]


def find_questions(query: str, limit: int = 8) -> list[dict]:
    """Ищет совпадения в заголовках, ключевых словах и ответах."""
    needle = " ".join(query.casefold().split())
    if not needle:
        return []
    terms = needle.split()
    ranked = []
    for question in ALL_QUESTIONS:
        title = question["title"].casefold()
        keywords = question["keywords"].casefold()
        answer = question["answer"].casefold()
        haystack = f"{title} {keywords} {answer}"
        score = sum(term in title for term in terms) * 4
        score += sum(term in keywords for term in terms) * 3
        score += sum(term in answer for term in terms)
        if needle in haystack:
            score += 2
        if score:
            ranked.append((score, question))
    ranked.sort(key=lambda item: item[0], reverse=True)
    return [question for _, question in ranked[:limit]]
